import argparse
import csv
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(description="Summarize object tracking CSV metrics.")
    parser.add_argument(
        "--metrics",
        type=str,
        default="data/output/tracking_metrics.csv",
        help="Path to metrics CSV generated by tracker_app.py.",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    path = Path(args.metrics)

    if not path.exists():
        raise FileNotFoundError(f"Metrics file not found: {path}")

    rows = []
    with path.open("r", newline="", encoding="utf-8") as file:
        reader = csv.DictReader(file)
        for row in reader:
            rows.append(row)

    if not rows:
        print("No metrics rows found.")
        return

    tracked_rows = [row for row in rows if row["success"] == "1"]
    fps_values = [float(row["fps"]) for row in rows if row["fps"]]
    final_distance = float(rows[-1]["path_px"]) if rows[-1]["path_px"] else 0.0
    success_rate = (len(tracked_rows) / len(rows)) * 100
    average_fps = sum(fps_values) / len(fps_values) if fps_values else 0.0

    print("Tracking Metrics Summary")
    print("------------------------")
    print(f"Total frames: {len(rows)}")
    print(f"Tracked frames: {len(tracked_rows)}")
    print(f"Success rate: {success_rate:.2f}%")
    print(f"Average FPS: {average_fps:.2f}")
    print(f"Estimated path length: {final_distance:.2f}px")


if __name__ == "__main__":
    main()
