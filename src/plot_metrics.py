import argparse
import csv
from pathlib import Path
from typing import Any

import numpy as np


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Comprehensive object tracking CSV metrics analysis.")
    parser.add_argument(
        "--metrics",
        type=str,
        default="data/output/tracking_metrics.csv",
        help="Path to metrics CSV generated by tracker_app.py.",
    )
    parser.add_argument(
        "--yolo-metrics",
        type=str,
        default="data/output/yolo_tracking_metrics.csv",
        help="Path to YOLO metrics CSV generated by yolo_tracker.py.",
    )
    parser.add_argument(
        "--plot",
        action="store_true",
        help="Generate visualization plot of tracking metrics.",
    )
    parser.add_argument(
        "--plot-3d",
        action="store_true",
        help="Generate 3D trajectory plot (requires yolo metrics with x,y coords).",
    )
    parser.add_argument(
        "--heatmap",
        action="store_true",
        help="Generate heatmap of object positions.",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/output/plots",
        help="Directory to save plots.",
    )
    return parser.parse_args()


def compute_statistics(rows: list[dict[str, str]]) -> dict[str, float] | None:
    if not rows:
        return None

    tracked_rows = [row for row in rows if row.get("success", "0") == "1"]
    fps_values = [float(row["fps"]) for row in rows if row.get("fps") and row["fps"] != "NaN"]
    path_values = [float(row.get("path_px", row.get("path_m", 0))) for row in rows
                   if row.get("path_px") or row.get("path_m")]

    success_rate = (len(tracked_rows) / len(rows)) * 100
    average_fps = sum(fps_values) / len(fps_values) if fps_values else 0.0
    total_path_length = path_values[-1] if path_values else 0.0
    average_path_per_frame = total_path_length / len(rows) if rows else 0.0

    return {
        "total_frames": len(rows),
        "tracked_frames": len(tracked_rows),
        "success_rate": success_rate,
        "average_fps": average_fps,
        "total_path_px": total_path_length,
        "average_path_per_frame": average_path_per_frame,
        "fps_std": float(np.std(fps_values)) if fps_values else 0.0,
        "min_fps": min(fps_values) if fps_values else 0.0,
        "max_fps": max(fps_values) if fps_values else 0.0,
    }


def compute_yolo_statistics(rows: list[dict[str, str]]) -> dict[str, float] | None:
    if not rows:
        return None

    tracked_rows = [row for row in rows if row.get("class") != "all" and int(row.get("track_id", 0)) > 0]
    conf_values = [float(row.get("confidence", 0)) for row in rows if row.get("confidence")]

    total_detections = len(rows)
    unique_ids = len(set(row.get("track_id", 0) for row in rows if row.get("track_id") and row["track_id"].isdigit()))

    success_rate = (len(tracked_rows) / total_detections) * 100 if total_detections else 0.0
    average_confidence = sum(conf_values) / len(conf_values) if conf_values else 0.0
    min_confidence = min(conf_values) if conf_values else 0.0
    max_confidence = max(conf_values) if conf_values else 0.0

    return {
        "total_detections": total_detections,
        "unique_tracks": unique_ids,
        "success_rate": success_rate,
        "average_confidence": average_confidence,
        "min_confidence": min_confidence,
        "max_confidence": max_confidence,
    }


def print_summary(title: str, stats: dict[str, float] | None, is_yolo: bool = False) -> None:
    if stats is None:
        print("No data found.")
        return

    print(f"\n{title}")
    print("=" * len(title))
    if is_yolo:
        print(f"Total detections: {stats.get('total_detections', 'N/A')}")
        print(f"Unique tracks: {stats.get('unique_tracks', 'N/A')}")
    else:
        print(f"Total frames: {stats.get('total_frames', 'N/A')}")
        print(f"Tracked frames: {stats.get('tracked_frames', 'N/A')}")
    print(f"Success rate: {stats.get('success_rate', 0):.2f}%")
    if not is_yolo:
        print(f"Average FPS: {stats.get('average_fps', 0):.2f}")
        print(f"FPS std dev: {stats.get('fps_std', 0):.2f}")
        print(f"Min FPS: {stats.get('min_fps', 0):.2f}")
        print(f"Max FPS: {stats.get('max_fps', 0):.2f}")
        print(f"Total path: {stats.get('total_path_px', 0):.2f}")
        print(f"Average path per frame: {stats.get('average_path_per_frame', 0):.2f}")
    else:
        print(f"Average confidence: {stats.get('average_confidence', 0):.4f}")
        print(f"Min confidence: {stats.get('min_confidence', 0):.4f}")
        print(f"Max confidence: {stats.get('max_confidence', 0):.4f}")


def main() -> None:
    args = parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    rows: list[dict[str, str]] = []
    yolo_rows: list[dict[str, str]] = []

    metrics_path = Path(args.metrics)
    yolo_metrics_path = Path(args.yolo_metrics)

    if metrics_path.exists():
        with metrics_path.open("r", newline="", encoding="utf-8") as file:
            reader = csv.DictReader(file)
            for row in reader:
                rows.append(row)

    if yolo_metrics_path.exists():
        with yolo_metrics_path.open("r", newline="", encoding="utf-8") as file:
            reader = csv.DictReader(file)
            for row in reader:
                yolo_rows.append(row)

    if rows:
        print_summary("Classical Tracker Metrics Summary", compute_statistics(rows))
    else:
        print("No classical tracker metrics found.")

    if yolo_rows:
        yolo_stats = compute_yolo_statistics(yolo_rows)
        print_summary("YOLO Tracker Metrics Summary", yolo_stats, is_yolo=True)
    else:
        print("No YOLO tracker metrics found.")

    if args.plot:
        import matplotlib.pyplot as plt

        if rows:
            fps_vals = [float(row["fps"]) for row in rows if row.get("fps") and row["fps"] != "NaN"]
            path_vals = [float(row.get("path_px", row.get("path_m", 0))) for row in rows
                         if row.get("path_px") or row.get("path_m")]

            plt.figure(figsize=(12, 8))

            # FPS over frames
            plt.subplot(2, 2, 1)
            plt.plot(fps_vals, color="tab:blue")
            plt.title("FPS Over Frames")
            plt.xlabel("Frame")
            plt.ylabel("FPS")
            plt.grid(True, alpha=0.3)

            # Path length over frames
            plt.subplot(2, 2, 2)
            plt.plot(path_vals, color="tab:orange")
            plt.title("Path Length Over Frames")
            plt.xlabel("Frame")
            plt.ylabel("Path")
            plt.grid(True, alpha=0.3)

            # FPS distribution
            plt.subplot(2, 2, 3)
            plt.hist(fps_vals, bins=30, color="tab:green", alpha=0.7, edgecolor="black")
            plt.title("FPS Distribution")
            plt.xlabel("FPS")
            plt.ylabel("Frequency")
            plt.grid(True, alpha=0.3)

            # Path length distribution
            plt.subplot(2, 2, 4)
            plt.hist(path_vals, bins=30, color="tab:red", alpha=0.7, edgecolor="black")
            plt.title("Path Length Distribution")
            plt.xlabel("Path Length")
            plt.ylabel("Frequency")
            plt.grid(True, alpha=0.3)

            plt.tight_layout()
            plot_path = output_dir / "tracking_metrics_plot.png"
            plt.savefig(plot_path, dpi=150)
            print(f"\nPlot saved to {plot_path}")
            plt.close()

        if yolo_rows:
            print("\nYOLO metrics plot support coming soon - CSV data available for analysis.")

    if args.plot_3d and yolo_rows:
        try:
            import matplotlib.pyplot as plt
            from mpl_toolkits.mplot3d import Axes3D  # noqa: F401

            fig = plt.figure(figsize=(10, 8))
            ax = fig.add_subplot(111, projection="3d")

            track_data: dict[int, list[tuple[float, float, float]]] = {}
            for row in yolo_rows:
                track_id = int(row.get("track_id", 0))
                if track_id > 0:
                    x = float(row.get("center_x", 0))
                    y = float(row.get("center_y", 0))
                    frame = float(row.get("frame", 0))
                    if track_id not in track_data:
                        track_data[track_id] = []
                    track_data[track_id].append((x, y, frame))

            colors = plt.cm.tab20(np.linspace(0, 1, len(track_data)))
            has_labels = False
            for (track_id, points), color in zip(track_data.items(), colors):
                if len(points) > 1:
                    xs, ys, zs = zip(*points)
                    ax.plot(xs, ys, zs, label=f"Track {track_id}", color=color, alpha=0.7)
                    has_labels = True

            ax.set_xlabel("X (pixels)")
            ax.set_ylabel("Y (pixels)")
            ax.set_zlabel("Frame")
            ax.set_title("3D Trajectory Visualization")
            if has_labels:
                ax.legend(bbox_to_anchor=(1.05, 1), loc="upper left")

            plot_path = output_dir / "tracking_3d_plot.png"
            plt.savefig(plot_path, dpi=150, bbox_inches="tight")
            print(f"3D plot saved to {plot_path}")
            plt.close()

        except ImportError:
            print("3D plotting requires mpl_toolkits. Install with: pip install matplotlib")

    if args.heatmap and (rows or yolo_rows):
        try:
            import matplotlib.pyplot as plt

            fig, axes = plt.subplots(1, 2 if rows and yolo_rows else 1, figsize=(14, 6))
            if not isinstance(axes, np.ndarray):
                axes = [axes]

            idx = 0
            if rows:
                x_vals = [float(row.get("center_x", 0)) for row in rows if row.get("center_x")]
                y_vals = [float(row.get("center_y", 0)) for row in rows if row.get("center_y")]
                if x_vals and y_vals:
                    heatmap, xedges, yedges = np.histogram2d(x_vals, y_vals, bins=50)
                    extent = [xedges[0], xedges[-1], yedges[0], yedges[-1]]
                    im = axes[idx].imshow(heatmap.T, extent=extent, origin="lower", cmap="hot", aspect="auto")
                    axes[idx].set_title("Classical Tracker - Position Heatmap")
                    axes[idx].set_xlabel("X (pixels)")
                    axes[idx].set_ylabel("Y (pixels)")
                    plt.colorbar(im, ax=axes[idx])
                    idx += 1

            if yolo_rows:
                x_vals = [float(row.get("center_x", 0)) for row in yolo_rows if row.get("center_x")]
                y_vals = [float(row.get("center_y", 0)) for row in yolo_rows if row.get("center_y")]
                if x_vals and y_vals:
                    heatmap, xedges, yedges = np.histogram2d(x_vals, y_vals, bins=50)
                    extent = [xedges[0], xedges[-1], yedges[0], yedges[-1]]
                    im = axes[idx].imshow(heatmap.T, extent=extent, origin="lower", cmap="hot", aspect="auto")
                    axes[idx].set_title("YOLO Tracker - Position Heatmap")
                    axes[idx].set_xlabel("X (pixels)")
                    axes[idx].set_ylabel("Y (pixels)")
                    plt.colorbar(im, ax=axes[idx])

            plt.tight_layout()
            plot_path = output_dir / "tracking_heatmap.png"
            plt.savefig(plot_path, dpi=150)
            print(f"Heatmap saved to {plot_path}")
            plt.close()

        except Exception as e:
            print(f"Error generating heatmap: {e}")


if __name__ == "__main__":
    main()